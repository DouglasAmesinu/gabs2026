// ── Claude API proxy ─────────────────────────────────────────────────────
// Keeps the Anthropic API key server-side; index.html calls this instead of
// api.anthropic.com directly. Key comes from Secret Manager via defineSecret,
// bound at runtime through the `secrets` option below.
exports.claudeProxy = onRequest({secrets: [ANTHROPIC_KEY]}, async (req, res) => {
  res.set("Access-Control-Allow-Origin", "https://gabsconnect.com");
  res.set("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.set("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    res.status(204).send("");
    return;
  }
  if (req.method !== "POST") {
    res.status(405).send("Method not allowed");
    return;
  }

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": ANTHROPIC_KEY.value(),
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify(req.body),
    });
    const data = await response.json();
    res.status(response.status).json(data);
  } catch (err) {
    logger.error("Proxy error:", err);
    res.status(500).json({error: "Proxy request failed"});
  }
});
